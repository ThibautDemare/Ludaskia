/* Fabrique l'ExerciseType d'une paire : QCM mono-mode à DEUX options. */
function homophoneType(paire: PaireHomophone): ExerciseType {
	const items = [
		...paire.phrasesA.map((phrase) => ({ phrase, reponse: paire.options[0] })),
		...paire.phrasesB.map((phrase) => ({ phrase, reponse: paire.options[1] })),
	];
	return {
		modes: MODE_QCM,
		generate(): Exercise {
			const { phrase, reponse } = choice(items);
			return {
				type: 'qcm',
				question: phrase,
				answer: reponse,
				choices: sample([...paire.options], 2), // les deux graphies, jamais une faute
				explication: paire.explication,
			};
		},
		check: (exercise, input) => checkAnswer(exercise, input),
	};
}

